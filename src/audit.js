const C = require('./crypto');
const { checkInfoBinding } = require('./attest');

const REPO = 'https://github.com/buyinofficial/buyin-engine';

function imageOf(appCompose) {
    const m = String(appCompose || '').match(/ghcr\.io\/[\w./-]+@sha256:[0-9a-f]{64}/);
    return m ? m[0] : null;
}

function auditReport(info, records, keyCount, base) {
    const a = info.attestation;
    const binding = checkInfoBinding(info);
    const recomputed = a && a.appCompose ? C.sha256hex(a.appCompose) : null;
    const image = a ? imageOf(a.appCompose) : null;
    const L = [];
    L.push(`# BUY-IN engine — live audit report`);
    L.push('');
    L.push(`This page is generated by the hold'em game engine itself, from inside a TEE (Intel TDX confidential VM on Phala Cloud, dstack).`);
    L.push(`Everything below can be re-checked independently. Raw data: [${base}/info](${base}/info) · [${base}/records/head](${base}/records/head) · [${base}/records/keys](${base}/records/keys)`);
    L.push(`Audit guide (threat model, step-by-step checks): ${REPO}/blob/main/AUDIT.md`);
    L.push('');
    L.push('## Live facts');
    L.push('');
    L.push(`| Item | Value |`);
    L.push(`|---|---|`);
    L.push(`| Engine | ${info.name} ${info.version} (mode \`${info.mode}\`) |`);
    L.push(`| Source | ${REPO} (tag \`v${info.version}\`) |`);
    L.push(`| Image (pinned by digest in the measured compose) | ${image ? '`' + image + '`' : 'n/a'} |`);
    L.push(`| Compose hash in attestation | ${a && a.composeHash ? '`' + a.composeHash + '`' : 'n/a'} |`);
    L.push(`| SHA-256 of the measured compose, recomputed here | ${recomputed ? '`' + recomputed + '`' + (recomputed === a.composeHash ? ' — matches' : ' — DOES NOT MATCH') : 'n/a'} |`);
    L.push(`| TDX quote report_data | ${a ? '`' + a.reportData + '`' : 'n/a'} |`);
    L.push(`| report_data = SHA-256(engine public keys) | ${a ? (binding.length ? 'FAILED: ' + binding.join('; ') : 'yes — the signing key was created inside this TEE') : 'no attestation (not running in a TEE)'} |`);
    L.push(`| Engine signing key fingerprint | \`${info.keys.sigFp}\` |`);
    L.push(`| Hand records kept in the TEE | ${records ? `${records.hands} hands, ${records.count} chain lines, head \`${records.head}\`` : 'n/a'} |`);
    L.push(`| Engine keys in the record chain | ${keyCount} (one per engine start) |`);
    L.push(`| Phala attestation report | ${a && a.appId ? `https://trust.phala.com/app/${a.appId}` : 'n/a'} |`);
    L.push('');
    L.push('## Check it yourself (no trust in the operator needed)');
    L.push('');
    L.push(`1. **The hardware quote is genuine Intel TDX.** POST \`{"hex": <attestation.quote from /info>}\` to \`https://cloud-api.phala.com/api/v1/attestations/verify\` → \`quote.verified: true\`. Or verify locally with Intel DCAP (\`dcap-qvl\`).`);
    L.push(`2. **The engine key belongs to that TEE.** The quote's \`report_data\` (bytes 568–600 of the quote) equals \`SHA-256(stableStringify({ ecdh, sig }))\` over the two public JWKs in \`/info\` (\`src/attest.js\` \`reportDataFor\`). The private keys never leave the TEE.`);
    L.push(`3. **The TEE runs the published code.** \`SHA-256(attestation.appCompose)\` equals \`composeHash\`, which the TEE measures into RTMR3 at boot (the Phala report replays the event log). The compose pins the image by digest; rebuilding tag \`v${info.version}\` from GitHub reproduces that digest (README → "Rebuild the image yourself").`);
    L.push(`4. **Every hand result is the engine's.** Each hand record is signed with the attested key; \`node src/verify.js record.json key.json\` replays the hand from the committed seed and fails on any difference.`);
    L.push(`5. **No record can be removed later.** Records are a hash chain on the TEE's encrypted disk; \`/records/head\` only grows. Save the head and compare later. Any hand's public receipt (chain position and hashes, no cards) is at \`/records/receipt/<handId>\`.`);
    L.push(`6. **Players verify their own hands here, not on the operator's site.** [${base}/table/verify.html](${base}/table/verify.html) is served by this TEE. It fetches the player's records with the player's own key signature (\`POST /records/mine\`, no operator token) and replays them in the browser with the engine files this TEE runs (\`/table/engine/*.js\`, the repository files wrapped for a script tag).`);
    L.push('');
    L.push('## What the operator cannot do');
    L.push('');
    L.push('- See anyone\'s hole cards or the undealt board during a hand (cards exist only inside the TEE; hole cards leave it encrypted to each player\'s own browser key).');
    L.push('- Choose or change the deck (seed committed before the hand, mixed with players\' own random values, 52 card commitments published at hand start).');
    L.push('- Bet, call or raise for a player (every chip-moving action needs that player\'s signature; the operator can only fold/check on timeout, and the record shows it).');
    L.push('- Change a result or a payout after the fact (records signed by the attested key, replayable, kept in an append-only chain).');
    L.push('- Swap in a different engine unnoticed (a different engine has a different key without this attestation; the player\'s browser compares the game\'s engine key with this page\'s attested key).');
    L.push('');
    L.push('## What the operator still controls (outside the engine)');
    L.push('');
    L.push('- Who may sit at a table, connection handling (can disconnect a player), wallets and deposits.');
    L.push('- Player identity: the operator runs login, so collusion between accounts is analysed after the fact from the signed records.');
    L.push('- Availability: the operator can stop the service; it cannot make a running hand come out differently.');
    L.push('');
    return L.join('\n') + '\n';
}

module.exports = { auditReport, imageOf };
