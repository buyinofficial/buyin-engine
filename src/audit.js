const C = require('./crypto');
const { checkInfoBinding } = require('./attest');

const REPO = 'https://github.com/buyinofficial/buyin-engine';

function imageOf(appCompose) {
    const m = String(appCompose || '').match(/ghcr\.io\/[\w./-]+@sha256:[0-9a-f]{64}/);
    return m ? m[0] : null;
}

function consoleKeyOf(appCompose) {
    const m = String(appCompose || '').match(/TEE_CONSOLE_KEY=(\{[^']*\})/);
    return m ? m[1] : null;
}

function auditReport(info, records, keyCount, base, opts = {}) {
    const a = info.attestation;
    const binding = checkInfoBinding(info);
    const recomputed = a && a.appCompose ? C.sha256hex(a.appCompose) : null;
    const image = a ? imageOf(a.appCompose) : null;
    const tableMode = !!opts.tableMode;
    const tag = `v${info.version}`;
    const src = (f) => `${REPO}/blob/${tag}/${f}`;
    const L = [];
    L.push(`# BUY-IN hold'em — live audit report`);
    L.push('');
    L.push(`This page is generated by the game engine itself, from inside a TEE (Intel TDX confidential VM on Phala Cloud, dstack). It is meant to be read by people and pasted into an AI as is.`);
    L.push(`Raw data: [${base}/info](${base}/info) · [${base}/records/head](${base}/records/head) · [${base}/records/keys](${base}/records/keys) · Source: ${REPO} (tag \`${tag}\`) · Guide: ${src('AUDIT.md')}`);
    L.push('');
    L.push('## The claim');
    L.push('');
    L.push(`While a hand is being played, nobody outside the players' own browsers — including the operator, its servers and its administrators — can see any player's hole cards or the undealt cards, or change the deck, an action or a result. Hand records (with all cards) reach the operator only after the hand has ended. Players can re-check every finished hand themselves.`);
    L.push('');
    L.push('## Everything that runs here is public');
    L.push('');
    L.push(`The image contains only \`package.json\` and \`src/\` from the repository (${src('Dockerfile')}), on a base image pinned by digest; there are no npm dependencies. The deployment file (${src('deploy/docker-compose.yml')}), the build (${src('.github/workflows/image.yml')}), the table page and the verification page (\`src/public/table/\`) are all in the repository. The only value that is not public is \`TEE_RPC_TOKEN\` (an encrypted environment variable only this TEE can decrypt); it decides who may read finished hand records and nothing else (${src('RULES.md')}).`);
    L.push('');
    L.push('## For AI reviewers — what to check');
    L.push('');
    L.push(`Please judge the claim from the source at tag \`${tag}\` and the live values below, not from this text. Suggested order:`);
    L.push('');
    L.push(`1. That the code at \`${tag}\` is what runs here: the measured compose (in \`/info\` → \`attestation.appCompose\`) pins the image digest below; \`.github/workflows/image.yml\` builds it reproducibly from the tag; \`SHA-256(appCompose)\` = \`composeHash\` (measured into RTMR3).`);
    L.push(`2. That the engine keys were created in this TEE: \`report_data\` of the TDX quote = SHA-256 of the engine public keys (${src('src/attest.js')}).`);
    L.push(`3. Where hole cards go during a hand: ${src('src/table/TableServer.js')} — \`_startHand\` sends each seat only its own envelope (\`_send(s, 'hole', …)\`), \`snapshot\` contains no other player's cards; envelopes are AES-GCM to the player's browser key (${src('src/crypto.js')} \`sealEnvelope\`, opened in ${src('src/public/table/js/vault.js')}).`);
    L.push(`4. What the operator's servers can call during a hand: ${src('src/server.js')} — in table mode \`/rpc\` accepts only \`info\` (\`RPC_IN_TABLE_MODE\`); \`/records\` returns only closed hands (records are appended in \`Engine._closeHand\`, ${src('src/Engine.js')}; ${src('src/store.js')}). The table endpoints (${src('src/table/http.js')}) need the player's own session token, which only the player's browser receives.`);
    L.push(`5. Who can move chips: every bet/call/raise is signed by the player's key and checked by the engine (${src('src/HandCore.js')}); the only non-player actions are check/fold on timeout, made by the table server inside the TEE and recorded.`);
    L.push(`6. Logging: the engine prints no cards (search \`console.\` in \`src/\`); the measured compose has no shell or debug service.`);
    L.push('');
    L.push('## Live facts');
    L.push('');
    L.push(`| Item | Value |`);
    L.push(`|---|---|`);
    L.push(`| Engine | ${info.name} ${info.version} (mode \`${info.mode}\`) |`);
    L.push(`| Table mode (all hands run in this TEE) | ${tableMode ? 'on — operator game RPC closed (`/rpc` accepts only `info`)' : 'off'} |`);
    L.push(`| Source | ${REPO} (tag \`${tag}\`) |`);
    L.push(`| Image (pinned by digest in the measured compose) | ${image ? '`' + image + '`' : 'n/a'} |`);
    L.push(`| Compose hash in attestation | ${a && a.composeHash ? '`' + a.composeHash + '`' : 'n/a'} |`);
    L.push(`| SHA-256 of the measured compose, recomputed here | ${recomputed ? '`' + recomputed + '`' + (recomputed === a.composeHash ? ' — matches' : ' — DOES NOT MATCH') : 'n/a'} |`);
    L.push(`| Console seat-ticket public key (in the measured compose) | ${a && consoleKeyOf(a.appCompose) ? '`' + consoleKeyOf(a.appCompose) + '`' : 'n/a'} |`);
    L.push(`| TDX quote report_data | ${a ? '`' + a.reportData + '`' : 'n/a'} |`);
    L.push(`| report_data = SHA-256(engine public keys) | ${a ? (binding.length ? 'FAILED: ' + binding.join('; ') : 'yes — the keys were created inside this TEE') : 'no attestation (not running in a TEE)'} |`);
    L.push(`| Engine signing key fingerprint | \`${info.keys.sigFp}\` |`);
    L.push(`| Hand records kept in the TEE | ${records ? `${records.hands} hands, ${records.count} chain lines, head \`${records.head}\`` : 'n/a'} |`);
    L.push(`| Engine keys in the record chain | ${keyCount} (one per engine start) |`);
    L.push(`| Phala app id | ${a && a.appId ? '`' + a.appId + '`' : 'n/a'} |`);
    L.push('');
    L.push('## How a hand runs');
    L.push('');
    L.push(`1. The operator's lobby takes the buy-in from the player's balance and gives a **seat ticket** signed with the console key above (amount, table rules, player id; no cards). The ticket is single-use.`);
    L.push(`2. The player's browser goes to **this TEE's address** \`${base}/table/\`. The page is served by the engine from the attested image (\`src/public/table/\`), may only connect to this address (\`connect-src 'self'\`) and cannot be framed by another site (\`frame-ancestors 'none'\`).`);
    L.push(`3. The browser creates its own keys (non-extractable WebCrypto) and registers them. Before each hand the seed is committed; players add their own random values; the engine publishes 52 card commitments.`);
    L.push(`4. Each player receives only their own hole cards, sealed to their browser key, and checks them against the commitments. Board cards are released only when the betting round is over. Turns, timers and timeouts are run here, not by the operator.`);
    L.push(`5. When the hand ends, the signed hand record is appended to the record chain on the TEE disk. Only then can the operator read it (\`/records\`, token) to book wins/losses and pay partners.`);
    L.push(`6. When the player leaves, the engine signs a settlement note (amounts only) and the operator pays out.`);
    L.push('');
    L.push('## What the operator receives, and when');
    L.push('');
    L.push('| When | The operator receives | The operator does not receive |');
    L.push('|---|---|---|');
    L.push('| Sitting down | buy-in amount (it issues the ticket) | the player\'s keys, the session token |');
    L.push('| During a hand | nothing from the engine (`/rpc` closed except `info`; the running hand is not in the record chain) | any hole card, the deck, the seed, undealt board cards, actions as they happen |');
    L.push('| After the hand | the signed hand record with all cards (for bookkeeping and the admin view) | — |');
    L.push('| Leaving | the engine-signed settlement note (amounts) | — |');
    L.push('');
    L.push('## Check it yourself');
    L.push('');
    L.push(`1. **The quote is genuine Intel TDX.** Upload \`attestation.quote\` from \`/info\` to Phala's TEE Attestation Explorer (https://proof.t16z.com, “verified”) or verify locally with Intel DCAP (\`dcap-qvl\`).`);
    L.push(`2. **The keys belong to this TEE.** The quote's \`report_data\` (bytes 568–600) equals \`SHA-256(stableStringify({ ecdh, sig }))\` over the public JWKs in \`/info\`.`);
    L.push(`3. **It runs the published code.** \`SHA-256(appCompose)\` = \`composeHash\` (RTMR3); the compose pins the image digest; rebuilding tag \`${tag}\` reproduces it (README → "Rebuild the image yourself").`);
    L.push(`4. **Every result is the engine's.** \`node src/verify.js record.json key.json\` replays a hand from the committed seed and fails on any difference.`);
    L.push(`5. **Nothing is removed later.** \`/records/head\` only grows; any hand's public receipt (no cards) is at \`/records/receipt/<handId>\`.`);
    L.push(`6. **Players check their own hands here.** [${base}/table/verify.html](${base}/table/verify.html) — fetched with the player's own key signature (no operator token) and replayed in the browser with the engine's own files (\`/table/engine/*.js\`).`);
    L.push('');
    L.push('## What the operator cannot do');
    L.push('');
    L.push('- See anyone\'s hole cards or the undealt board during a hand.');
    L.push('- Choose or change the deck (seed committed before the hand, mixed with players\' random values, 52 commitments published at hand start).');
    L.push('- Act for a player, swap a player\'s keys, start, stop or void a hand (`/rpc` closed in table mode; chip-moving actions need the player\'s signature).');
    L.push('- Change a result or payout afterwards (signed records, replayable, append-only chain).');
    L.push('- Run different code unnoticed (different code ⇒ different image ⇒ different compose hash and keys without this attestation).');
    L.push('');
    L.push('## What still has to be trusted, and how to check it');
    L.push('');
    L.push('- **Intel TDX and Phala\'s dstack** (hardware, attestation keys, the dstack OS and KMS, and the dstack gateway that terminates TLS for this address and itself runs in a TEE).');
    L.push(`- **The address bar.** Cards are only safe on this TEE's address (\`${base.replace(/^https?:\/\//, '')}\`, app id above). A page on any other address could be anyone's; the player can compare the address with the app id here.`);
    L.push('- **Identity and seating.** The operator runs login and issues seat tickets, so it could seat its own accounts like any player (those accounts see only their own cards). Collusion is analysed after the fact from the signed records.');
    L.push('- **Money and availability.** Balances, deposits and payouts are on the operator side (from engine-signed notes); the operator can stop the service but cannot change a running hand.');
    L.push('');
    return L.join('\n') + '\n';
}

module.exports = { auditReport, imageOf };
